"""Renders the gallery of the examples off screen: for each boolean case, its operands and the
three results side by side (one color per face, the edges of the BREP in black), and a few
meshes with their triangles; writes the PNG images and `gallery.md` that gathers them.

    python gallery.py --out gallery

On Linux without a display, run it under `xvfb-run -a`. The CI publishes the folder as an
artifact of the build.
"""
from __future__ import annotations

import argparse
import math
import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import gbs_examples as ex  # noqa: E402

brep = ex.brep


def boolean_rows(out: pathlib.Path):
    rows = []
    for case in ex.CASES:
        t0 = time.perf_counter()
        r = ex.run(case)
        seconds = time.perf_counter() - t0
        p = ex.plot_case(r, case, off_screen=True)
        image = out / f"boolean_{case.name}.png"
        p.screenshot(str(image))
        p.close()
        cells = []
        for op in ex.OPERATIONS:
            if op in r.shapes:
                mesh = brep.mesh(r.model, r.shapes[op])
                faces = len(brep.explore_faces(r.model, r.shapes[op]))
                valid = "valid" if brep.check(r.model, r.shapes[op]).ok() else "**invalid**"
                closed = "closed" if mesh.open_sides() == 0 else f"**{mesh.open_sides()} open sides**"
                cells.append(f"{faces} faces, V = {mesh.volume():.4g}, {valid}, {closed}")
            else:
                cells.append(f"**error**: {r.errors[op]}")
        rows.append((case, image.name, cells, seconds))
        print(f"{case.name}: {seconds:.2f} s", flush=True)
    return rows


MESHES = [
    ("sphere", "Sphere, deflection 1e-2 of its diagonal", lambda m: ex.sphere(m, 1.0), 1e-2),
    ("torus", "Torus", lambda m: ex.torus(m, 3.0, 1.0), 1e-2),
    ("cone", "Cone (apex)", lambda m: ex.cone(m, 1.0, 2.0), 1e-2),
    ("cylinder", "Cylinder: triangles long along the generatrices", lambda m: ex.cylinder(m, 1.0, 4.0), 1e-2),
    ("box_minus_sphere", "Box minus a sphere: trimmed faces", lambda m: brep.cut(m, ex.box(m, (0, 0, 0), (2, 3, 4)), ex.sphere(m, 1.5, (2, 3, 4), (1, 1, 1))).shape, 1e-2),
    ("steinmetz", "Equal crossed cylinders, fused", lambda m: brep.fuse(m, *ex._steinmetz(m)).shape, 1e-2),
]


def mesh_rows(out: pathlib.Path):
    import pyvista as pv

    rows = []
    for name, title, build, relative in MESHES:
        m = brep.Model()
        s = build(m)
        b = brep.bounding_box(m, s)
        deflection = relative * math.dist(b[0], b[1])  # (bounding_box: (min, max))
        options = brep.MeshOptions(deflection=deflection)
        p = pv.Plotter(off_screen=True, window_size=(800, 600))
        poly, mesh = ex.face_polydata(m, s, options)
        if poly is not None:
            p.add_mesh(poly, color="#9ecae1", show_edges=True, edge_color="#3a5f7d", line_width=0.5, smooth_shading=False)
        lines = ex.edge_lines(m, s)
        if lines is not None:
            p.add_mesh(lines, color="#222222", line_width=2)
        p.add_text(title, font_size=9)
        p.view_isometric()
        image = out / f"mesh_{name}.png"
        p.screenshot(str(image))
        p.close()
        rows.append((title, image.name, len(mesh.triangles), deflection, mesh.open_sides(), mesh.volume()))
        print(f"mesh {name}: {len(mesh.triangles)} triangles", flush=True)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="gallery", help="output folder")
    args = parser.parse_args()
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    lines = ["# GBS gallery", "", "Generated by `docs/sources/examples/gallery.py`.", "", "## Booleans", "",
             "Operands (blue: a, orange: b), then `fuse`, `cut` and `common`: one color per face, the edges of the BREP in black (not the seams of the periodic surfaces).", ""]
    for case, image, cells, seconds in boolean_rows(out):
        lines += [f"### {case.title}", ""]
        if case.note:
            lines += [f"*{case.note}*", ""]
        lines += [f"![{case.name}]({image})", "", "| fuse | cut | common | time |", "|---|---|---|---|",
                  f"| {cells[0]} | {cells[1]} | {cells[2]} | {seconds:.2f} s |", ""]
    lines += ["## Meshes", "", "| Shape | Triangles | Deflection | Open sides | Volume |", "|---|---|---|---|---|"]
    rows = mesh_rows(out)
    for title, image, n, deflection, open_sides, volume in rows:
        lines.append(f"| {title} | {n} | {deflection:.3g} | {open_sides} | {volume:.5g} |")
    lines.append("")
    for title, image, *_ in rows:
        lines += [f"![{title}]({image})", ""]
    (out / "gallery.md").write_text("\n".join(lines))
    print(f"written {out / 'gallery.md'}")


if __name__ == "__main__":
    main()
